def _is_numeric(values: list[Any]) -> bool:
    seen = False
    for value in values:
        if value is None or (isinstance(value, float) and pd.isna(value)):
            continue
        if isinstance(value, bool):
            return False
        if not isinstance(value, (int, float)):
            return False
        seen = True
    return seen


def column_type(table: str, column: str, values: list[Any]) -> str:
    if column in common.DATE_COLUMNS.get(table, set()):
        return "DATE"
    if _is_numeric(values):
        return "DOUBLE"
    return "VARCHAR"


def collect() -> dict[str, dict[str, Any]]:
    client = TushareClient(rpm=195.0, retries=2)
    out: dict[str, dict[str, Any]] = {}
    for table, params in SAMPLES.items():
        fields, items = client.call(table, params, dataset=table, partition="__introspect__")
        columns: list[tuple[str, str]] = []
        for index, name in enumerate(fields):
            values = [row[index] for row in items]
            columns.append((name, column_type(table, name, values)))
        out[table] = {"columns": columns, "rows": len(items)}
        print(f"[introspect] {table}: {len(columns)} columns, {len(items)} sample rows", flush=True)
    return out


def render(tables: dict[str, dict[str, Any]]) -> str:
    lines: list[str] = [
        "-- WORK-513 DuckDB 规范化层 schema",
        "-- GENERATED by `python -m db.etl.introspect` from the live Tushare field",
        "-- lists (2026-11-22). Do not hand-edit: regenerate instead.",
        "",
        "PRAGMA threads=4;",
        "",
    ]
    for table in DDL_ORDER:
        info = tables[table]
        pk = common.TABLE_PK[table]
        # No DROP here: re-running the schema must never empty a table that the
        # caller is not about to reload (finding: a partial --load-only wiped
        # every other table). Use --full-refresh (DELETE + INSERT) to rebuild.
        lines.append(f"CREATE TABLE IF NOT EXISTS {table} (")
        parts = []
        for name, dtype in info["columns"]:
            parts.append(f'    "{name}" {dtype}')
        pk_cols = ", ".join(f'"{c}"' for c in pk if c in {n for n, _ in info["columns"]})
        if pk_cols:
            parts.append(f"    PRIMARY KEY ({pk_cols})")
        lines.append(",\n".join(parts))
        lines.append(");")
        lines.append("")
        for name, _dtype in info["columns"]:
            comment = UNIT_COMMENTS.get((table, name))
            if comment:
                lines.append(f"COMMENT ON COLUMN {table}.\"{name}\" IS '{comment}';")
        if any(UNIT_COMMENTS.get((table, name)) for name, _ in info["columns"]):
            lines.append("")

    lines += [
        "-- 复权价视图：查询期用 adj_factor 现算，不落盘复权价。",
        "-- qfq = close * adj_factor / 该股历史最大 adj_factor；hfq = close * adj_factor / 最小值。",
        "CREATE OR REPLACE VIEW v_daily_qfq AS",
        "WITH f AS (",
        "    SELECT ts_code, trade_date, adj_factor,",
        "           MAX(adj_factor) OVER (PARTITION BY ts_code) AS adj_max",
        "    FROM adj_factor",
        ")",
        "SELECT d.ts_code, d.trade_date, d.open, d.high, d.low, d.close, d.pre_close,",
        "       d.vol, d.amount, d.change, d.pct_chg,",
        "       ROUND(d.open  * f.adj_factor / NULLIF(f.adj_max, 0), 4) AS open_qfq,",
        "       ROUND(d.high  * f.adj_factor / NULLIF(f.adj_max, 0), 4) AS high_qfq,",
        "       ROUND(d.low   * f.adj_factor / NULLIF(f.adj_max, 0), 4) AS low_qfq,",
        "       ROUND(d.close * f.adj_factor / NULLIF(f.adj_max, 0), 4) AS close_qfq",
        "FROM daily d JOIN f ON d.ts_code = f.ts_code AND d.trade_date = f.trade_date;",
        "",
        "CREATE OR REPLACE VIEW v_daily_hfq AS",
        "WITH f AS (",
        "    SELECT ts_code, trade_date, adj_factor,",
        "           MIN(adj_factor) OVER (PARTITION BY ts_code) AS adj_min",
        "    FROM adj_factor",
        ")",
        "SELECT d.ts_code, d.trade_date, d.open, d.high, d.low, d.close, d.pre_close,",
        "       d.vol, d.amount, d.change, d.pct_chg,",
        "       ROUND(d.open  * f.adj_factor / NULLIF(f.adj_min, 0), 4) AS open_hfq,",
        "       ROUND(d.high  * f.adj_factor / NULLIF(f.adj_min, 0), 4) AS high_hfq,",
        "       ROUND(d.low   * f.adj_factor / NULLIF(f.adj_min, 0), 4) AS low_hfq,",
        "       ROUND(d.close * f.adj_factor / NULLIF(f.adj_min, 0), 4) AS close_hfq",
        "FROM daily d JOIN f ON d.ts_code = f.ts_code AND d.trade_date = f.trade_date;",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="python -m db.etl.introspect")
    parser.add_argument("--check", action="store_true", help="只校验，不写文件")
    args = parser.parse_args(argv)
    tables = collect()
    rendered = render(tables)
    if args.check:
        current = common.SCHEMA_SQL.read_text(encoding="utf-8")
        same = re.sub(r"\s+", " ", current) == re.sub(r"\s+", " ", rendered)
        print("schema up to date" if same else "schema DIFFERS from the live field lists")
        return 0 if same else 1
    common.SCHEMA_SQL.write_text(rendered, encoding="utf-8")
    print(f"[ok] wrote {common.SCHEMA_SQL}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
